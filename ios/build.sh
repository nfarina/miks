#!/usr/bin/env bash
# @chatwing
#
# Build, and optionally install, the iOS shell without opening Xcode.
#
# Xcode is a poor fit for the way this repo is worked on: almost every change
# is in the web layer, the native shell is deliberately thin, and needing a GUI
# to find out whether Swift still compiles means it usually doesn't get
# checked. Everything here is `xcodebuild` and `devicectl`, both of which ship
# with Xcode itself.
#
# Usage:
#   ios/build.sh              # build for a generic device (the compile check)
#   ios/build.sh sim          # build for the simulator — no signing required
#   ios/build.sh device       # build, then install onto the connected iPhone
#   ios/build.sh devices      # list what's plugged in, with their ids
#   ios/build.sh mac          # build the Mac app (Release), install it into
#                             # /Applications, and relaunch it if it was running.
#                             # That's the native target (<Scheme>Mac) where the
#                             # project has one, else the Mac Catalyst build.
#
# Projects in Xcode's JSON format (project.xcproj, Xcode 27.2+) sync their
# folders with the disk, so adding a Swift file never touches the project.
# Projects still generated by XcodeGen (project.yml) are regenerated first, for
# the same reason; drop project.yml once one is converted.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

MODE="${1:-generic}"

# Derive everything from the project rather than hardcoding a name, so this
# file can be shared across apps unchanged.
if [[ -f project.yml ]]; then
  command -v xcodegen >/dev/null || {
    echo "xcodegen not found — brew install xcodegen" >&2
    exit 1
  }
  xcodegen generate >/dev/null
fi

PROJECT="$(ls -d *.xcodeproj | head -1)"
SCHEME="$(basename "$PROJECT" .xcodeproj)"

case "$MODE" in
  devices)
    xcrun devicectl list devices
    exit 0
    ;;
  sim)
    DESTINATION="generic/platform=iOS Simulator"
    ;;
  mac)
    # The native Mac app (ios/SharedMac) is its own target. Projects still on
    # Mac Catalyst build the iOS target for it instead.
    # Read from the project file: `xcodebuild -list` resolves Swift packages
    # into Xcode's DerivedData, which is the folder this script stays out of.
    # The first pattern is the JSON format, the second a pbxproj.
    if grep -qE "\"name\": \"${SCHEME}Mac\"|name = ${SCHEME}Mac;" "$PROJECT"/project.*; then
      SCHEME="${SCHEME}Mac"
      DESTINATION="generic/platform=macOS"
    else
      DESTINATION="generic/platform=macOS,variant=Mac Catalyst"
    fi
    ;;
  *)
    DESTINATION="generic/platform=iOS"
    ;;
esac

echo "Building $SCHEME for $DESTINATION"

# Every mode builds into our own (gitignored) build/ folder rather than Xcode's
# DerivedData. Each built app there is another copy Launch Services can launch
# by bundle ID — that's how a stale Dock icon once opened a months-old Catalyst
# build instead of /Applications/Harbor.app. A folder named *.noindex is never
# indexed by Spotlight, which keeps the copies in it from being registered.
# The Mac app gets installed and used day to day, so it's a Release build.
DERIVED=build/DerivedData.noindex
EXTRA_ARGS=(-derivedDataPath "$DERIVED")
if [[ "$MODE" == "mac" ]]; then
  EXTRA_ARGS+=(-configuration Release)
fi

# -allowProvisioningUpdates lets Xcode mint or refresh the provisioning
# profile itself. Without it, a newly registered App ID (or a newly added
# capability like push) fails to sign with an error that reads like a code
# problem rather than a portal one.
xcodebuild \
  -project "$PROJECT" \
  -scheme "$SCHEME" \
  -destination "$DESTINATION" \
  "${EXTRA_ARGS[@]}" \
  -allowProvisioningUpdates \
  -quiet \
  build

if [[ "$MODE" == "mac" ]]; then
  APP="$(xcodebuild -project "$PROJECT" -scheme "$SCHEME" -destination "$DESTINATION" \
    "${EXTRA_ARGS[@]}" -showBuildSettings 2>/dev/null |
    awk '/ BUILT_PRODUCTS_DIR =/{d=$3} / FULL_PRODUCT_NAME =/{n=$3} END{print d "/" n}')"

  [[ -d "$APP" ]] || {
    echo "Couldn't find the built app at $APP" >&2
    exit 1
  }

  NAME="$(basename "$APP" .app)"
  BUNDLE_ID="$(/usr/libexec/PlistBuddy -c "Print CFBundleIdentifier" "$APP/Contents/Info.plist")"
  EXECUTABLE="$(/usr/libexec/PlistBuddy -c "Print CFBundleExecutable" "$APP/Contents/Info.plist")"

  # Quit whichever copy is running — this one, or an old one Xcode launched
  # from DerivedData — politely first, so it can save state. Only ask if it's
  # running: `tell application id` launches an app that isn't.
  WAS_RUNNING=false
  if pgrep -xq "$EXECUTABLE"; then
    WAS_RUNNING=true
    echo "Quitting $NAME"
    osascript -e "tell application id \"$BUNDLE_ID\" to quit" >/dev/null 2>&1 || true
    for _ in {1..20}; do
      pgrep -xq "$EXECUTABLE" || break
      sleep 0.25
    done
    pkill -x "$EXECUTABLE" 2>/dev/null || true
  fi

  # Replace the installed app, and any Finder alias standing in for it (which
  # would otherwise sit next to the real thing, still pointing at DerivedData).
  #
  # Every copy Launch Services knows about stays launchable by bundle ID, which
  # is how a Dock icon whose path has gone stale finds its app, so it can pick
  # an old build. Copies in the Trash get registered again whenever the Trash
  # is looked at, so the old one is deleted rather than trashed: it's build
  # output, and the copy we install replaces it.
  LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
  for OLD in "/Applications/$NAME.app" "/Applications/$NAME"; do
    if [[ -e "$OLD" || -L "$OLD" ]]; then
      echo "Replacing $OLD"
      "$LSREGISTER" -u "$OLD" 2>/dev/null || true
      rm -rf "$OLD"
    fi
  done

  echo "Installing /Applications/$NAME.app"
  ditto "$APP" "/Applications/$NAME.app"
  "$LSREGISTER" -u "$APP" 2>/dev/null || true
  "$LSREGISTER" -f "/Applications/$NAME.app"

  if [[ "$WAS_RUNNING" == true ]]; then
    echo "Relaunching $NAME"
    open "/Applications/$NAME.app"
  fi

  echo "Installed $NAME."
  exit 0
fi

if [[ "$MODE" != "device" ]]; then
  echo "Built $SCHEME."
  exit 0
fi

APP="$(xcodebuild -project "$PROJECT" -scheme "$SCHEME" -destination "$DESTINATION" \
  "${EXTRA_ARGS[@]}" -showBuildSettings 2>/dev/null |
  awk '/ BUILT_PRODUCTS_DIR =/{d=$3} / FULL_PRODUCT_NAME =/{n=$3} END{print d "/" n}')"

[[ -d "$APP" ]] || {
  echo "Couldn't find the built app at $APP" >&2
  exit 1
}

# Which device to install onto. Parsed from JSON rather than the table, whose
# columns contain spaces in every interesting field — the name, the model, and
# the two-word state — so column-position parsing silently picks the wrong row.
# It will happily hand you a paired Apple Watch.
#
# Pass a name fragment or identifier to disambiguate:
#   ios/build.sh device "Nick's iPhone"
DEVICE_QUERY="${2:-${IOS_DEVICE:-}}"

DEVICE_JSON="$(mktemp)"
trap 'rm -f "$DEVICE_JSON"' EXIT
xcrun devicectl list devices --json-output "$DEVICE_JSON" >/dev/null 2>&1

DEVICE="$(python3 - "$DEVICE_JSON" "$DEVICE_QUERY" <<'PY'
import json, sys

path, query = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else "")
devices = json.load(open(path))["result"]["devices"]

def usable(d):
    hw, conn = d.get("hardwareProperties", {}), d.get("connectionProperties", {})
    return (
        hw.get("reality") == "physical"          # not a simulator
        and hw.get("platform") == "iOS"          # not the watch
        and conn.get("pairingState") == "paired"
        and conn.get("tunnelState") != "unavailable"  # a phone belonging to someone else
    )

def name(d):
    return d.get("deviceProperties", {}).get("name", "?")

matches = [d for d in devices if usable(d)]
if query:
    q = query.lower()
    matches = [d for d in matches if q in name(d).lower() or q in d["identifier"].lower()]

if not matches:
    print("NONE", file=sys.stderr)
    sys.exit(1)
if len(matches) > 1:
    print("Several devices match. Re-run with one of:", file=sys.stderr)
    for d in matches:
        print(f'  ios/build.sh device "{name(d)}"', file=sys.stderr)
    sys.exit(2)

print(matches[0]["identifier"])
print(name(matches[0]), file=sys.stderr)
PY
)" || {
  echo "Pick a device (or connect one): ios/build.sh devices" >&2
  exit 1
}

echo "Installing onto $DEVICE"
xcrun devicectl device install app --device "$DEVICE" "$APP"
